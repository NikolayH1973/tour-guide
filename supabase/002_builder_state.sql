-- =========================================================
-- 002: «исходник» тура для конструктора
-- data    — готовый trip.json, его читает приложение туриста;
-- builder — состояние формы конструктора (текст программы, рейсы, отели,
--           что введено руками), чтобы «Открыть» восстанавливал форму один в один.
-- Как исходный код и собранная программа: правим исходник, показываем результат.
-- Туристу builder не отдаётся: get_tour возвращает только data.
-- =========================================================
alter table public.tours add column if not exists builder jsonb;
